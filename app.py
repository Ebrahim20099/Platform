@app.route("/course/<int:course_id>/exam", methods=["POST"])
def submit_exam(course_id):
    course = Course.query.get_or_404(course_id)
    if g.user is None or not CourseEnrollment.query.filter_by(
        user_id=g.user["id"], course_id=course_id
    ).first():
        return redirect(url_for("home"))

    score = 0
    objective_total = 0
    essay_total = 0
    for question in course.exam_questions:
        answer = request.form.get(f"question_{question.id}", "").strip()
        if question.question_type == "essay":
            essay_total += 1
            submission = EssaySubmission.query.filter_by(user_id=g.user["id"], course_id=course_id, question_id=question.id).first()
            if submission is None:
                submission = EssaySubmission(user_id=g.user["id"], course_id=course_id, question_id=question.id)
                db.session.add(submission)
            submission.answer = answer
            submission.score = 0
            submission.feedback = ""
            submission.status = "pending"
            submission.updated_at = datetime.utcnow()
            db.session.commit()
        else:
            objective_total += question.marks
            if answer == question.correct_option:
                score += question.marks

    report = StudentExamReport.query.filter_by(user_id=g.user["id"], course_id=course_id).first()
    if report is None:
        report = StudentExamReport(user_id=g.user["id"], course_id=course_id)
        db.session.add(report)
    report.score = score
    report.total = objective_total
    report.result_status = "ready" if essay_total == 0 else "pending"
    report.review_summary = "تم التصحيح" if essay_total == 0 else "قيد التصحيح"
    report.achievements = report.achievements or ""
    report.weak_points = report.weak_points or ""
    report.admin_analysis = report.admin_analysis or ""
    db.session.commit()

    return redirect(url_for("course_content", course_id=course_id))


