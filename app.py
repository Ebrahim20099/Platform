@app.route("/course-content/<int:item_id>/file")
def course_content_file(item_id):
    if g.user is None:
        return redirect(url_for("login"))

    item = ContentItem.query.get_or_404(item_id)
    enrolled = CourseEnrollment.query.filter_by(
        user_id=g.user["id"], course_id=item.course_id
    ).first()
    if not enrolled or item.content_type != "pdf":
        abort(404)

    file_name = os.path.basename(item.body.strip())
    file_path = os.path.join(app.config["CONTENT_UPLOAD_FOLDER"], file_name)
    if not os.path.isfile(file_path):
        original_name = file_name.split("_", 2)[-1]
        fallback_path = os.path.join(app.config["CONTENT_UPLOAD_FOLDER"], original_name)
        if not os.path.isfile(fallback_path):
            abort(404)
        file_path = fallback_path
    return send_file(
        file_path,
        mimetype="application/pdf",
        as_attachment=True,
        conditional=False,
        etag=False,
        max_age=0,
        download_name=f"{re.sub(r'[\\/:*?\"<>|]+', '-', item.title).strip(' .') or 'document'}.pdf",
    )


