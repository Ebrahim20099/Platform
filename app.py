def get_challenge_leaders():
    results = db.session.execute(text("""
        SELECT id, name, email, study_type, score
        FROM users
        WHERE score > 0
        ORDER BY score DESC, id ASC
    """)).fetchall()

    leaders = {"center": [], "online": []}
    for row in results:
        bucket = row["study_type"]
        if bucket not in leaders:
            continue
        leaders[bucket].append({
            "id": row["id"],
            "name": row["name"],
            "email": row["email"],
            "score": row["score"],
            "study_type": row["study_type"],
        })

    return {
        "center": leaders["center"][:3],
        "online": leaders["online"][:3],
    }


