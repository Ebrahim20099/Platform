@app.route("/forum", methods=["GET", "POST"])
def forum():
    if g.user is None:
        return redirect(url_for("login"))

    status_filter = request.args.get("status", "all")
    valid_filters = {"all", "open", "answered"}
    if status_filter not in valid_filters:
        status_filter = "all"

    if request.method == "POST":
        if not CourseEnrollment.query.filter_by(user_id=g.user["id"]).first():
            flash("لا يمكنك إرسال سؤال في المنتدي إلا إذا كنت مشتركًا في كورس واحد على الأقل", "error")
            return redirect(url_for("courses"))

        question = request.form.get("question", "").strip()
        if not question:
            flash("اكتب سؤالك أولاً", "error")
            return redirect(url_for("forum"))

        image_path = ""
        image_file = request.files.get("image")
        if image_file and image_file.filename:
            os.makedirs(os.path.join(app.root_path, "static", "uploads", "forum"), exist_ok=True)
            safe_name = secure_filename(image_file.filename)
            filename = f"forum_{datetime.utcnow().timestamp()}_{safe_name}"
            image_file.save(os.path.join(app.root_path, "static", "uploads", "forum", filename))
            image_path = f"/static/uploads/forum/{filename}"

        db.session.add(StudentForumQuestion(user_id=g.user["id"], question=question, image=image_path))
        db.session.commit()
        flash("تم إرسال السؤال إلى الإدارة", "success")
        return redirect(url_for("forum"))

    sql = """
        SELECT q.id, q.question, q.answer, q.image, q.created_at, q.answered_at, q.answered_by,
               u.name AS student_name, u.grade AS student_grade
        FROM student_forum_questions q
        JOIN users u ON u.id = q.user_id
    """
    params = []
    if status_filter == "open":
        sql += " WHERE q.answer IS NULL OR q.answer = ''"
    elif status_filter == "answered":
        sql += " WHERE q.answer IS NOT NULL AND q.answer != ''"
    sql += " ORDER BY q.created_at DESC"

    questions = get_db().execute(sql, params).fetchall()
    return render_template("forum.html", questions=questions, status_filter=status_filter)


@app.route("/api/verify-code", methods=["POST"])
def verify_code():
    from datetime import datetime
    from flask import jsonify
    from school_app.models import AccessCode

    if g.user is None:
        return jsonify(success=False, message="سجل دخولك الأول عشان تشترك في الكورس"), 401

    data = request.get_json(silent=True) or {}
    course_id = data.get("course_id")
    code_value = (data.get("code") or "").strip().upper()
    if not course_id or not code_value:
        return jsonify(success=False, message="من فضلك ادخل الكود"), 400

    access_code = AccessCode.query.filter_by(course_id=course_id, code=code_value).first()
    if not access_code:
        return jsonify(success=False, message="الكود غير صحيح"), 404
    if access_code.is_used:
        return jsonify(success=False, message="الكود ده مستخدم قبل كده"), 409

    if CourseEnrollment.query.filter_by(user_id=g.user["id"], course_id=course_id).first():
        return jsonify(success=True, already_subscribed=True, redirect_url=url_for("course_content", course_id=course_id))

    access_code.is_used = True
    access_code.used_at = datetime.utcnow()
    db.session.add(CourseEnrollment(user_id=g.user["id"], course_id=course_id))
    db.session.commit()
    unlocked = session.get("unlocked_courses", [])
    if int(course_id) not in unlocked:
        unlocked.append(int(course_id))
    session["unlocked_courses"] = unlocked
    return jsonify(success=True, redirect_url=url_for("course_content", course_id=course_id))


