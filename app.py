def send_reset_email(email, token):
    mail_server = os.environ.get("MAIL_SERVER")
    mail_port = int(os.environ.get("MAIL_PORT", "587"))
    mail_username = os.environ.get("MAIL_USERNAME")
    mail_password = os.environ.get("MAIL_PASSWORD")
    mail_sender = os.environ.get("MAIL_SENDER", mail_username or "noreply@example.com")

    if not mail_server or not mail_username or not mail_password:
        return False, token

    reset_url = url_for("reset_password", token=token, _external=True)
    message = EmailMessage()
    message["Subject"] = "إعادة تعيين كلمة المرور"
    message["From"] = mail_sender
    message["To"] = email
    message.set_content(
        f"عزيزي الطالب،\n\n"
        f"تم إنشاء رابط لإعادة تعيين كلمة المرور الخاص بك.\n"
        f"الرابط: {reset_url}\n\n"
        "إذا لم تطلب هذا التغيير، يمكنك تجاهل الرسالة."
    )

    try:
        with smtplib.SMTP(mail_server, mail_port) as smtp:
            smtp.starttls()
            smtp.login(mail_username, mail_password)
            smtp.send_message(message)
        return True, reset_url
    except Exception:
        return False, reset_url


@app.route("/forgot-password", methods=["GET", "POST"])
def forgot_password():
    if request.method == "POST":
        email = request.form.get("email", "").strip().lower()
        user = db.session.execute(
            text("SELECT * FROM users WHERE email = :email"),
            {"email": email},
        ).fetchone()

        if user is not None:
            token = secrets.token_urlsafe(24)
            expires_at = datetime.utcnow() + timedelta(minutes=30)
            db.session.execute(
                text("UPDATE users SET reset_token = :token, reset_token_expires_at = :expires_at WHERE id = :user_id"),
                {"token": token, "expires_at": expires_at.strftime("%Y-%m-%d %H:%M:%S"), "user_id": user["id"]},
            )
            db.session.commit()

            sent, detail = send_reset_email(email, token)
            if sent:
                return render_template("forgot_password.html", success="تم إرسال رابط إعادة التعيين إلى بريدك الإلكتروني.")
            return render_template("forgot_password.html", success="تم إنشاء رابط استعادة كلمة المرور. استخدم هذا الرابط في الاختبار المحلي:", reset_link=detail)

        return render_template(
            "forgot_password.html",
            success="إذا كان البريد مسجلًا، سيتم إرسال رابط استعادة كلمة المرور إليه.",
        )

    return render_template("forgot_password.html")


