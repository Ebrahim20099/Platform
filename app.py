def init_db():
    dialect = db.engine.dialect.name
    inspector = db.inspect(db.engine)

    if "users" not in inspector.get_table_names():
        if dialect == "postgresql":
            db.session.execute(text("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    phone TEXT NOT NULL,
                    email TEXT NOT NULL UNIQUE,
                    grade TEXT NOT NULL,
                    study_type TEXT NOT NULL,
                    password TEXT NOT NULL,
                    score INTEGER DEFAULT 0,
                    guardian_phone TEXT DEFAULT '',
                    reset_token TEXT DEFAULT '',
                    reset_token_expires_at TIMESTAMP,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """))
        else:
            db.session.execute(text("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL,
                    phone TEXT NOT NULL,
                    email TEXT NOT NULL UNIQUE,
                    grade TEXT NOT NULL,
                    study_type TEXT NOT NULL,
                    password TEXT NOT NULL,
                    score INTEGER DEFAULT 0,
                    guardian_phone TEXT DEFAULT '',
                    reset_token TEXT DEFAULT '',
                    reset_token_expires_at TIMESTAMP,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """))
        db.session.commit()

    user_columns = {column["name"] for column in inspector.get_columns("users")}
    for column_name, definition in {
        "score": "INTEGER DEFAULT 0",
        "created_at": "TIMESTAMP DEFAULT CURRENT_TIMESTAMP",
        "reset_token": "TEXT DEFAULT ''",
        "reset_token_expires_at": "TIMESTAMP",
        "guardian_phone": "TEXT DEFAULT ''",
    }.items():
        if column_name not in user_columns:
            db.session.execute(text(f"ALTER TABLE users ADD COLUMN {column_name} {definition}"))
    db.session.commit()

    for table_name, ddl in {
        "challenge_scores": """
            CREATE TABLE IF NOT EXISTS challenge_scores (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL,
                score INTEGER NOT NULL DEFAULT 0,
                reason TEXT,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """,
        "student_exam_reports": """
            CREATE TABLE IF NOT EXISTS student_exam_reports (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL,
                course_id INTEGER NOT NULL,
                score INTEGER NOT NULL DEFAULT 0,
                total INTEGER NOT NULL DEFAULT 0,
                result_status VARCHAR(30) NOT NULL DEFAULT 'pending',
                review_summary TEXT DEFAULT '',
                achievements TEXT DEFAULT '',
                weak_points TEXT DEFAULT '',
                admin_analysis TEXT DEFAULT '',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """,
        "essay_submissions": """
            CREATE TABLE IF NOT EXISTS essay_submissions (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL,
                course_id INTEGER NOT NULL,
                question_id INTEGER NOT NULL,
                answer TEXT DEFAULT '',
                score INTEGER NOT NULL DEFAULT 0,
                feedback TEXT DEFAULT '',
                status VARCHAR(30) NOT NULL DEFAULT 'pending',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """,
        "student_forum_questions": """
            CREATE TABLE IF NOT EXISTS student_forum_questions (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL,
                question TEXT NOT NULL,
                image TEXT DEFAULT '',
                answer TEXT DEFAULT '',
                answered_by TEXT DEFAULT '',
                answered_at TIMESTAMP,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """,
    }.items():
        if table_name not in inspector.get_table_names():
            if dialect == "postgresql" and table_name in {"challenge_scores", "student_exam_reports", "essay_submissions", "student_forum_questions"}:
                create_sql = ddl.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
            else:
                create_sql = ddl
            db.session.execute(text(create_sql))
    db.session.commit()

    for table_name, extra_columns in {
        "student_exam_reports": {"result_status": "VARCHAR(30) DEFAULT 'pending'", "review_summary": "TEXT DEFAULT ''"},
        "essay_submissions": {"score": "INTEGER NOT NULL DEFAULT 0", "feedback": "TEXT DEFAULT ''", "status": "VARCHAR(30) DEFAULT 'pending'"},
        "student_forum_questions": {"question": "TEXT NOT NULL DEFAULT ''", "answer": "TEXT DEFAULT ''", "image": "TEXT DEFAULT ''", "answered_by": "TEXT DEFAULT ''", "answered_at": "TIMESTAMP"},
    }.items():
        columns = {column["name"] for column in inspector.get_columns(table_name)}
        for column_name, definition in extra_columns.items():
            if column_name not in columns:
                db.session.execute(text(f"ALTER TABLE {table_name} ADD COLUMN {column_name} {definition}"))
    db.session.commit()


